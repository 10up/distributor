<?php
/**
 * EnqueueScript tests
 *
 * @package distributor
 */

// phpcs:disable WordPressVIPMinimum.Functions.RestrictedFunctions.file_ops_unlink, WordPressVIPMinimum.Functions.RestrictedFunctions.directory_rmdir, WordPressVIPMinimum.Functions.RestrictedFunctions.file_ops_file_put_contents -- Tests write a temporary build asset file.

namespace Distributor\IntegrationTests;

use WP_Scripts;
use WP_UnitTestCase;
use Distributor\EnqueueScript;

/**
 * Integration tests for the EnqueueScript class.
 *
 * @group EnqueueScript
 */
class Test_EnqueueScript extends WP_UnitTestCase {
	/**
	 * Script file name, without the extension, used by the tests.
	 *
	 * @var string
	 */
	const SCRIPT_FILE_NAME = 'dt-test-enqueue-script';

	/**
	 * Script handle used by the tests.
	 *
	 * @var string
	 */
	const SCRIPT_HANDLE = 'dt-test-enqueue-script';

	/**
	 * Scripts registry in place before the test.
	 *
	 * @var WP_Scripts|null
	 */
	protected $original_wp_scripts;

	/**
	 * Directories created by the test, deepest first.
	 *
	 * @var string[]
	 */
	protected $created_directories = array();

	/**
	 * Set up.
	 */
	public function set_up() {
		parent::set_up();

		// Use an empty scripts registry for each test.
		$this->original_wp_scripts = $GLOBALS['wp_scripts'] ?? null;
		$GLOBALS['wp_scripts']     = new WP_Scripts();
		remove_action( 'wp_default_scripts', 'wp_default_scripts' );
	}

	/**
	 * Tear down.
	 */
	public function tear_down() {
		$GLOBALS['wp_scripts'] = $this->original_wp_scripts;

		$asset_file = $this->get_asset_file_path();
		if ( file_exists( $asset_file ) ) {
			unlink( $asset_file ); // phpcs:ignore WordPress.WP.AlternativeFunctions.unlink_unlink
		}

		foreach ( $this->created_directories as $directory ) {
			rmdir( $directory ); // phpcs:ignore WordPress.WP.AlternativeFunctions.file_system_operations_rmdir
		}

		parent::tear_down();
	}

	/**
	 * Get the path of the test script's asset file.
	 *
	 * @return string Asset file path.
	 */
	protected function get_asset_file_path() {
		return DT_PLUGIN_PATH . 'dist/js/' . self::SCRIPT_FILE_NAME . '.asset.php';
	}

	/**
	 * Write an asset file for the test script, as generated by the build.
	 *
	 * The build output is not committed, so the file is written by the test.
	 *
	 * @param array $asset Asset data.
	 */
	protected function write_asset_file( $asset ) {
		$asset_file = $this->get_asset_file_path();

		// The dist directories only exist once the plugin is built.
		foreach ( array( dirname( $asset_file ), dirname( $asset_file, 2 ) ) as $directory ) {
			if ( ! is_dir( $directory ) ) {
				$this->created_directories[] = $directory;
			}
		}
		wp_mkdir_p( dirname( $asset_file ) );

		file_put_contents( $asset_file, '<?php return ' . var_export( $asset, true ) . ';' ); // phpcs:ignore WordPress.WP.AlternativeFunctions.file_system_operations_file_put_contents, WordPress.PHP.DevelopmentFunctions.error_log_var_export
	}

	/**
	 * Get a registered script.
	 *
	 * @return \_WP_Dependency|false Registered script.
	 */
	protected function get_registered_script() {
		return wp_scripts()->query( self::SCRIPT_HANDLE, 'registered' );
	}

	/**
	 * Test registering a script.
	 */
	public function test_script_registration(): void {
		$script = new EnqueueScript( self::SCRIPT_HANDLE, self::SCRIPT_FILE_NAME );

		$this->assertSame( $script, $script->register(), 'Register should be chainable.' );
		$this->assertSame( self::SCRIPT_HANDLE, $script->get_script_handle(), 'Script handle should be returned.' );

		$registered = $this->get_registered_script();
		$this->assertNotFalse( $registered, 'Script should be registered.' );
		$this->assertSame( plugin_dir_url( DT_PLUGIN_FULL_FILE ) . 'dist/js/' . self::SCRIPT_FILE_NAME . '.js', $registered->src, 'Script should be loaded from the dist directory.' );
		$this->assertSame( array(), $registered->deps, 'Script should have no dependencies without an asset file.' );
		$this->assertSame( DT_VERSION, $registered->ver, 'Script should use the plugin version without an asset file.' );
		$this->assertFalse( wp_script_is( self::SCRIPT_HANDLE, 'enqueued' ), 'Script should not be enqueued.' );
		$this->assertEmpty( $registered->textdomain, 'Translations should not be registered by default.' );
		$this->assertFalse( wp_scripts()->get_data( self::SCRIPT_HANDLE, 'group' ), 'Script should load in the header by default.' );
	}

	/**
	 * Test enqueuing a script registers it if needs be.
	 */
	public function test_script_enqueue(): void {
		$script = new EnqueueScript( self::SCRIPT_HANDLE, self::SCRIPT_FILE_NAME );

		$this->assertSame( $script, $script->enqueue(), 'Enqueue should be chainable.' );
		$this->assertTrue( wp_script_is( self::SCRIPT_HANDLE, 'registered' ), 'Script should be registered.' );
		$this->assertTrue( wp_script_is( self::SCRIPT_HANDLE, 'enqueued' ), 'Script should be enqueued.' );
	}

	/**
	 * Test enqueuing a script that is already registered.
	 */
	public function test_script_enqueue_registered_script(): void {
		$script = new EnqueueScript( self::SCRIPT_HANDLE, self::SCRIPT_FILE_NAME );
		$script->register_localize_data( 'dtTestData', array( 'key' => 'value' ) )->register();
		$script->enqueue();

		$this->assertTrue( wp_script_is( self::SCRIPT_HANDLE, 'enqueued' ), 'Script should be enqueued.' );
		$this->assertSame( 1, substr_count( wp_scripts()->get_data( self::SCRIPT_HANDLE, 'data' ), 'dtTestData' ), 'Script should not be registered twice.' );
	}

	/**
	 * Test the version is read from the asset file.
	 */
	public function test_custom_version(): void {
		$this->write_asset_file(
			array(
				'dependencies' => array(),
				'version'      => 'abc123',
			)
		);

		$script = new EnqueueScript( self::SCRIPT_HANDLE, self::SCRIPT_FILE_NAME );

		$this->assertSame( 'abc123', $script->get_version(), 'Version should be read from the asset file.' );

		$script->register();
		$this->assertSame( 'abc123', $this->get_registered_script()->ver, 'Script should be registered with the asset file version.' );
	}

	/**
	 * Test the version defaults to the plugin version without an asset file.
	 */
	public function test_default_version(): void {
		$script = new EnqueueScript( self::SCRIPT_HANDLE, self::SCRIPT_FILE_NAME );

		$this->assertSame( DT_VERSION, $script->get_version() );
	}

	/**
	 * Test custom dependencies are merged with those in the asset file.
	 */
	public function test_custom_dependencies(): void {
		$this->write_asset_file(
			array(
				'dependencies' => array( 'wp-element', 'wp-i18n' ),
				'version'      => 'abc123',
			)
		);

		$script = new EnqueueScript( self::SCRIPT_HANDLE, self::SCRIPT_FILE_NAME );

		$this->assertSame( $script, $script->dependencies( array( 'jquery' ) ), 'Dependencies should be chainable.' );
		$this->assertSame( array( 'jquery', 'wp-element', 'wp-i18n' ), $script->get_asset_file_data()['dependencies'], 'Custom dependencies should be merged with the asset file dependencies.' );

		$script->register();
		$this->assertSame( array( 'jquery', 'wp-element', 'wp-i18n' ), $this->get_registered_script()->deps, 'Script should be registered with all dependencies.' );
	}

	/**
	 * Test custom dependencies without an asset file.
	 */
	public function test_custom_dependencies_without_asset_file(): void {
		$script = new EnqueueScript( self::SCRIPT_HANDLE, self::SCRIPT_FILE_NAME );
		$script->dependencies( array( 'jquery' ) )->register();

		$this->assertSame( array( 'jquery' ), $this->get_registered_script()->deps );
	}

	/**
	 * Test script translations are registered.
	 */
	public function test_translations(): void {
		$script = new EnqueueScript( self::SCRIPT_HANDLE, self::SCRIPT_FILE_NAME );

		$this->assertSame( $script, $script->register_translations(), 'Register translations should be chainable.' );
		$script->register();

		$registered = $this->get_registered_script();
		$this->assertSame( 'distributor', $registered->textdomain, 'Script should use the plugin text domain.' );
		$this->assertSame( DT_PLUGIN_PATH . 'lang', $registered->translations_path, 'Script should load translations from the plugin lang directory.' );
	}

	/**
	 * Test localized data is added to the script.
	 */
	public function test_localize_data(): void {
		$script = new EnqueueScript( self::SCRIPT_HANDLE, self::SCRIPT_FILE_NAME );

		$this->assertSame( $script, $script->register_localize_data( 'dtTestData', array( 'key' => 'value' ) ), 'Register localize data should be chainable.' );
		$script->register();

		$this->assertSame( 'var dtTestData = {"key":"value"};', wp_scripts()->get_data( self::SCRIPT_HANDLE, 'data' ) );
	}

	/**
	 * Test the script can be loaded in the footer.
	 */
	public function test_load_script_in_footer(): void {
		$script = new EnqueueScript( self::SCRIPT_HANDLE, self::SCRIPT_FILE_NAME );

		$this->assertSame( $script, $script->load_in_footer(), 'Load in footer should be chainable.' );
		$script->register();

		$this->assertSame( 1, wp_scripts()->get_data( self::SCRIPT_HANDLE, 'group' ) );
	}
}
